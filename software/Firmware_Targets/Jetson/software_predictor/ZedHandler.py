"""Fast ZED native-YOLO ball detection and tracking API.

Model classes:
    0 = person
    1 = ball
"""

from __future__ import annotations

import math
import time
from collections import deque
from dataclasses import dataclass
from pathlib import Path

import pyzed.sl as sl

BALL_CLASS_ID = 1
DEFAULT_CONFIDENCE_PERCENT = 25.0
TIMING_WARMUP_FRAMES = 100
TIMING_WINDOW_FRAMES = 120
DEFAULT_DISPLAY_FPS = 30.0
DEFAULT_PRINT_FPS = 10.0
DEFAULT_DEPTH_STABILIZATION = 0
DEFAULT_TRACKING_COMPUTE = "cpu"
DEFAULT_DEPTH_MODE = "neural-light"


@dataclass(frozen=True, slots=True)
class ZedObject3D:
    """Minimal object returned by the real-time tracking path."""

    #stable id generated by this handler and preserved across short sdk id changes
    object_id: int

    #original class id from the detector
    raw_label: int

    #object center in the gravity-aligned zed world frame, in meters
    position: tuple[float, float, float]

    #detector confidence normalized to 0.0-1.0
    confidence: float

    #tracking state reported by the zed sdk
    tracking_state: object

    #true for one update when this stable id was remapped to a different sdk id
    identity_changed: bool


@dataclass(frozen=True, slots=True)
class ZedObject2D:
    """Debug-only image-space information returned by get_frame()."""

    #same stable id returned by get_objects()
    object_id: int

    #original class id from the detector
    raw_label: int

    #2d corners in left-camera pixel coordinates
    bounding_box_2d: tuple[tuple[float, float], ...]


@dataclass(frozen=True, slots=True)
class ZedCameraIntrinsics:
    """Rectified left-camera intrinsics used to project 3D points into the image."""

    #horizontal focal length in pixels
    fx: float

    #vertical focal length in pixels
    fy: float

    #horizontal optical center in pixels
    cx: float

    #vertical optical center in pixels
    cy: float

    #calibration image width
    width: int

    #calibration image height
    height: int


@dataclass(frozen=True, slots=True)
class ZedCameraPose:
    """Current left-camera pose inside the gravity-aligned ZED world frame."""

    #left-camera origin expressed in world coordinates, in meters
    position: tuple[float, float, float]

    #camera-to-world orientation quaternion stored as x, y, z, w
    orientation: tuple[float, float, float, float]


@dataclass(frozen=True, slots=True)
class ZedTimingStats:
    """Rolling application-level frame throughput statistics."""

    #wall-clock period between the two most recent completed object frames
    latest_seconds: float

    #mean completed-frame period over the rolling window
    mean_seconds: float

    #median completed-frame period over the rolling window
    median_seconds: float

    #95th percentile completed-frame period, useful as a slow-frame metric
    p95_seconds: float

    #number of post-warmup frame intervals currently in the window
    sample_count: int

    @property
    def latest_fps(self) -> float:
        """Instantaneous application FPS from the latest completed-frame interval."""
        return 1.0 / self.latest_seconds if self.latest_seconds > 0.0 else 0.0

    @property
    def mean_fps(self) -> float:
        """Rolling application FPS based on total frames divided by total wall time."""
        return 1.0 / self.mean_seconds if self.mean_seconds > 0.0 else 0.0

    @property
    def median_fps(self) -> float:
        """FPS corresponding to the median completed-frame period."""
        return 1.0 / self.median_seconds if self.median_seconds > 0.0 else 0.0

    @property
    def p95_frame_fps(self) -> float:
        """FPS corresponding to the 95th-percentile slow frame period."""
        return 1.0 / self.p95_seconds if self.p95_seconds > 0.0 else 0.0


@dataclass(slots=True)
class _TrackedIdentity:
    """Private state used to keep our object id stable across brief sdk id changes."""

    #stable id exposed to the rest of the program
    stable_id: int

    #current id assigned by the zed sdk
    sdk_id: int

    #last handler frame where this object was observed
    last_seen_frame: int

    #last valid 3d position used for reassociation
    x: float = 0.0
    y: float = 0.0
    z: float = 0.0

    #false until at least one finite 3d position has been received
    has_valid_position: bool = False

    #prevents one stable identity from being assigned to two detections in the same frame
    output_frame: int = -1

    #set for one output when the sdk id changes or is reused
    identity_changed: bool = False


def _check_success(status: sl.ERROR_CODE, operation: str) -> None:
    """Convert a ZED SDK error code into a normal Python exception."""

    if status != sl.ERROR_CODE.SUCCESS:
        raise RuntimeError(f"{operation} failed: {status}")


def _make_runtime_filter(confidence_percent: float) -> sl.CustomObjectDetectionRuntimeParameters:
    """Configure ZED so only ball detections are returned by the custom detector."""

    runtime = sl.CustomObjectDetectionRuntimeParameters()
    runtime.object_detection_properties.detection_confidence_threshold = confidence_percent

    #disable person detections by setting their required confidence to 100 percent
    person = sl.CustomObjectDetectionProperties()
    person.detection_confidence_threshold = 100.0
    if hasattr(person, "enabled"):
        person.enabled = False

    #allow ball detections at the requested confidence threshold
    ball = sl.CustomObjectDetectionProperties()
    ball.detection_confidence_threshold = confidence_percent
    if hasattr(ball, "enabled"):
        ball.enabled = True

    #a thrown ball moves freely in 3d, so never constrain the zed tracker to the ground plane
    if hasattr(ball, "is_grounded"):
        ball.is_grounded = False
    if hasattr(ball, "is_static"):
        ball.is_static = False

    #keep the sdk tracker responsive because the trajectory fitter handles its own smoothing/modeling
    if hasattr(ball, "velocity_smoothing_factor"):
        ball.velocity_smoothing_factor = 0.0
    if hasattr(ball, "min_velocity_threshold"):
        ball.min_velocity_threshold = 0.0
    if hasattr(ball, "prediction_timeout_s"):
        ball.prediction_timeout_s = 0.0
    if hasattr(ball, "min_confirmation_time_s"):
        ball.min_confirmation_time_s = 0.0

    runtime.object_class_detection_properties = {0: person, BALL_CLASS_ID: ball}
    return runtime


class ZedHandler:
    """Low-overhead wrapper around ZED SDK 5.5+ native YOLO detection.

    get_objects() is the hot path. It does not retrieve image pixels, read velocity,
    or convert 2D boxes.

    The handler keeps its own stable object IDs. If ZED temporarily loses an object
    and later gives it another native ID, nearby recent tracks are reassociated.

    get_frame() is the optional debug/display path.
    """

    def __init__(self, onnx_path: str | Path, confidence_percent: float = DEFAULT_CONFIDENCE_PERCENT, dynamic_input_size: int | None = None, svo_path: str | None = None, static_camera: bool = False, max_missing_frames: int = 5, max_reassociation_distance_m: float = 2.0, measure_framerate: bool = False, allow_reduced_precision_inference: bool = True, depth_stabilization: int = DEFAULT_DEPTH_STABILIZATION, tracking_compute: str = DEFAULT_TRACKING_COMPUTE, sdk_object_tracking: bool = True, depth_mode: str = DEFAULT_DEPTH_MODE) -> None:
        #validate arguments before opening the camera
        model_path = Path(onnx_path)
        if not model_path.is_file():
            raise FileNotFoundError(f"ONNX model not found: {model_path}")
        if not 0.0 <= confidence_percent <= 100.0:
            raise ValueError("confidence_percent must be between 0 and 100")
        if dynamic_input_size is not None and (dynamic_input_size <= 0 or dynamic_input_size % 32 != 0):
            raise ValueError("dynamic_input_size must be a positive multiple of 32")
        if max_missing_frames < 0:
            raise ValueError("max_missing_frames must not be negative")
        if max_reassociation_distance_m <= 0.0:
            raise ValueError("max_reassociation_distance_m must be positive")
        if not 0 <= depth_stabilization <= 100:
            raise ValueError("depth_stabilization must be between 0 and 100")
        if tracking_compute not in ("auto", "cpu", "gpu"):
            raise ValueError("tracking_compute must be auto, cpu, or gpu")
        if depth_mode not in ("neural-light", "performance"):
            raise ValueError("depth_mode must be neural-light or performance")

        #maximum number of missed camera frames where an identity can still be recovered
        self._max_missing_frames = max_missing_frames

        #squared threshold avoids taking a square root during every reassociation comparison
        self._max_reassociation_distance_sq = max_reassociation_distance_m**2

        #optional timing measures actual completed application frame throughput
        self._measure_framerate = measure_framerate

        #zed temporal object tracking can be disabled to benchmark a lighter app-side reassociation path
        self._sdk_object_tracking = sdk_object_tracking

        #wall time when the previous grab+object result finished
        self._last_completed_frame_ns: int | None = None

        #period between the two most recent completed object frames
        self._last_frame_period_ns: int | None = None

        #ignore startup frames because cuda/model/depth warmup makes them unrepresentative
        self._timing_warmup_remaining = TIMING_WARMUP_FRAMES

        #rolling completed-frame periods include sdk work and application work between frames
        self._timing_samples_ns: deque[int] = deque(maxlen=TIMING_WINDOW_FRAMES)

        #monotonic handler frame number used for identity age checks
        self._frame_number = 0

        #next stable id that will be exposed as ZedObject3D.object_id
        self._next_stable_id = 0

        #fast lookup from the sdk's current id to our persistent identity
        self._identities_by_sdk_id: dict[int, _TrackedIdentity] = {}

        #all live stable identities, including ones whose sdk id may have recently changed
        self._identities_by_stable_id: dict[int, _TrackedIdentity] = {}

        #zed objects container reused every frame to avoid reallocating it
        self._objects = sl.Objects()

        #camera runtime parameters reused by grab()
        self._runtime = sl.RuntimeParameters()

        #return object positions in the gravity-aligned world frame so fitting is independent of camera tilt
        self._runtime.measure3D_reference_frame = sl.REFERENCE_FRAME.WORLD

        #object retrieval filter reused by get_objects()
        self._object_runtime = _make_runtime_filter(confidence_percent)

        #true only after a successful grab()
        self._frame_ready = False

        #true only after get_objects() has retrieved detections for the current frame
        self._objects_ready = False

        #capture timestamp of the current image frame
        self._frame_timestamp_ns: int | None = None

        #debug image buffer is allocated lazily the first time get_frame() is called
        self._image_buffer: sl.Mat | None = None

        #camera intrinsics are read once and then cached
        self._intrinsics: ZedCameraIntrinsics | None = None

        #camera pose storage is allocated lazily because it is only needed for visualization
        self._camera_pose: sl.Pose | None = None

        #stable ids assigned to ball objects in the current sdk object list, in filtered ball order
        self._current_ball_stable_ids: list[int] = []

        #create the underlying zed camera
        self._zed = sl.Camera()
        input_type = sl.InputType()
        if svo_path:
            input_type.set_from_svo_file(svo_path)

        #configure the camera for the 100 hz trajectory pipeline
        init = sl.InitParameters(input_t=input_type)
        init.camera_resolution = sl.RESOLUTION.VGA
        init.camera_fps = 100
        #NEURAL_LIGHT is the fastest current neural mode; legacy PERFORMANCE is exposed for benchmarking
        init.depth_mode = sl.DEPTH_MODE.NEURAL_LIGHT if depth_mode == "neural-light" else sl.DEPTH_MODE.PERFORMANCE
        init.coordinate_units = sl.UNIT.METER
        init.coordinate_system = sl.COORDINATE_SYSTEM.RIGHT_HANDED_Y_UP
        init.depth_maximum_distance = 20
        #stabilization costs latency/work and the trajectory estimator already smooths over many samples
        init.depth_stabilization = depth_stabilization

        #use the sdk's cuda graph path when this sdk version exposes it
        if hasattr(init, "allow_depth_cuda_graph"):
            init.allow_depth_cuda_graph = True

        _check_success(self._zed.open(init), "Opening ZED camera")

        try:
            #world coordinates need positional tracking, but mapping/relocalization is unnecessary here
            positional_tracking = sl.PositionalTrackingParameters()
            positional_tracking.enable_imu_fusion = True
            positional_tracking.set_gravity_as_origin = True

            #GEN_3 is lightweight and does not depend on depth for camera motion estimation
            if hasattr(positional_tracking, "mode") and hasattr(sl, "POSITIONAL_TRACKING_MODE") and hasattr(sl.POSITIONAL_TRACKING_MODE, "GEN_3"):
                positional_tracking.mode = sl.POSITIONAL_TRACKING_MODE.GEN_3

            #area mapping is wasted work for this short-lived fixed world coordinate system
            if hasattr(positional_tracking, "enable_area_memory"):
                positional_tracking.enable_area_memory = False
            if hasattr(positional_tracking, "enable_pose_smoothing"):
                positional_tracking.enable_pose_smoothing = False

            #SDK 5.5 can keep GEN_3 work on CPU so the GPU is freer for YOLO and depth
            if tracking_compute != "auto" and hasattr(positional_tracking, "compute_preference"):
                preference_type = getattr(sl, "POSITIONAL_TRACKING_COMPUTE_PREFERENCE", None)
                if preference_type is not None:
                    preference_name = "PREFER_CPU" if tracking_compute == "cpu" else "PREFER_GPU"
                    if hasattr(preference_type, preference_name):
                        positional_tracking.compute_preference = getattr(preference_type, preference_name)

            if static_camera:
                positional_tracking.set_as_static = True
            _check_success(self._zed.enable_positional_tracking(positional_tracking), "Enabling positional tracking")

            #run the exported onnx model through the sdk's native yolo path
            detection = sl.ObjectDetectionParameters()
            detection.detection_model = sl.OBJECT_DETECTION_MODEL.CUSTOM_YOLOLIKE_BOX_OBJECTS
            detection.custom_onnx_file = str(model_path.resolve())
            detection.enable_tracking = sdk_object_tracking
            detection.enable_segmentation = False

            #YOLO already suppresses duplicate boxes; skip the SDK's extra 3d NMS pass
            if hasattr(detection, "filtering_mode") and hasattr(sl, "OBJECT_FILTERING_MODE") and hasattr(sl.OBJECT_FILTERING_MODE, "NONE"):
                detection.filtering_mode = sl.OBJECT_FILTERING_MODE.NONE
            if hasattr(detection, "prediction_timeout_s"):
                detection.prediction_timeout_s = 0.0

            #allow fp16 or other reduced precision inference when supported
            if hasattr(detection, "allow_reduced_precision_inference"):
                detection.allow_reduced_precision_inference = allow_reduced_precision_inference

            #only override the model input resolution when explicitly requested
            if dynamic_input_size is not None:
                detection.custom_onnx_dynamic_input_shape = sl.Resolution(dynamic_input_size, dynamic_input_size)

            _check_success(self._zed.enable_object_detection(detection), "Enabling native YOLO object detection")
        except Exception:
            self.close()
            raise

    def grab(self) -> bool:
        """Acquire the next frame without retrieving image pixels or object data."""

        if self._zed is None:
            raise RuntimeError("ZED camera is closed")

        #grab advances depth and other sdk processing but does not copy image pixels to python
        status = self._zed.grab(self._runtime)

        self._frame_ready = status == sl.ERROR_CODE.SUCCESS
        self._objects_ready = False
        self._current_ball_stable_ids.clear()

        if self._frame_ready:
            #increment only for real captured frames so identity age is measured in camera frames
            self._frame_number += 1

            #use the image clock so detections and trajectory measurements share capture time
            self._frame_timestamp_ns = int(self._zed.get_timestamp(sl.TIME_REFERENCE.IMAGE).get_nanoseconds())

        return self._frame_ready

    def get_objects(self) -> tuple[list[ZedObject3D], int]:
        """Return tracked balls from the latest grabbed frame with minimal Python work."""

        if self._zed is None:
            raise RuntimeError("ZED camera is closed")
        if not self._frame_ready:
            raise RuntimeError("Call grab() successfully before get_objects()")

        #retrieve_custom_objects may be the synchronization point for asynchronous sdk work
        status = self._zed.retrieve_custom_objects(self._objects, self._object_runtime)
        _check_success(status, "Retrieving ZED objects")

        #local references avoid repeated attribute lookups inside the per-object loop
        frame_number = self._frame_number
        results: list[ZedObject3D] = []
        append = results.append

        for obj in self._objects.object_list:
            #the runtime filter should already remove people, but keep this check as a cheap safeguard
            raw_label = int(obj.raw_label)
            if raw_label != BALL_CLASS_ID:
                continue

            #native id can change after a short tracking loss, so it stays private
            sdk_id = int(obj.id)

            #copy only the three position values needed by the trajectory code
            position = obj.position
            x = float(position[0])
            y = float(position[1])
            z = float(position[2])
            valid_position = math.isfinite(x) and math.isfinite(y) and math.isfinite(z)

            #native tracking is optional because this handler can reassociate detections by 3d proximity itself
            if self._sdk_object_tracking:
                identity = self._resolve_identity(sdk_id=sdk_id, x=x, y=y, z=z, position_is_valid=valid_position)
            else:
                identity = self._resolve_identity_untracked(x=x, y=y, z=z, position_is_valid=valid_position)
            identity.last_seen_frame = frame_number
            identity.output_frame = frame_number
            self._current_ball_stable_ids.append(identity.stable_id)

            #keep the previous good 3d point if this frame's depth temporarily becomes invalid
            if valid_position:
                identity.x = x
                identity.y = y
                identity.z = z
                identity.has_valid_position = True

            #return only information needed by the real-time trajectory path
            append(ZedObject3D(object_id=identity.stable_id, raw_label=raw_label, position=(x, y, z), confidence=float(obj.confidence) * 0.01, tracking_state=obj.tracking_state, identity_changed=identity.identity_changed))

            #identity_changed is a one-update notification
            identity.identity_changed = False

        #get_frame() is now allowed to use the sdk objects from this exact frame
        self._objects_ready = True

        #remove identity bookkeeping that is too old to be useful for reassociation
        self._prune_identities()

        if self._frame_timestamp_ns is None:
            raise RuntimeError("Frame timestamp is unavailable")

        if self._measure_framerate:
            #measure delivered application throughput at the point a complete object frame is ready
            completed_ns = time.perf_counter_ns()

            if self._last_completed_frame_ns is not None:
                frame_period_ns = completed_ns - self._last_completed_frame_ns
                self._last_frame_period_ns = frame_period_ns

                #cuda and neural-network startup is intentionally excluded from rolling statistics
                if self._timing_warmup_remaining > 0:
                    self._timing_warmup_remaining -= 1
                else:
                    self._timing_samples_ns.append(frame_period_ns)

            self._last_completed_frame_ns = completed_ns

        return results, self._frame_timestamp_ns

    def grab_and_get_objects(self) -> tuple[list[ZedObject3D], int] | None:
        """Convenience hot-path call that grabs one frame and immediately gets objects."""

        if not self.grab():
            return None
        return self.get_objects()

    def get_frame(self) -> tuple[object, list[ZedObject2D]]:
        """Return the current left image and current ball boxes for debugging/visualization."""

        if self._zed is None:
            raise RuntimeError("ZED camera is closed")
        if not self._frame_ready:
            raise RuntimeError("Call grab() successfully before get_frame()")
        if not self._objects_ready:
            raise RuntimeError("Call get_objects() for the current frame before get_frame()")

        #allocate one image buffer only when the debug display is actually used
        if self._image_buffer is None:
            self._image_buffer = sl.Mat()

        #retrieve pixels only on display frames, never on the normal 100 hz object path
        _check_success(self._zed.retrieve_image(self._image_buffer, sl.VIEW.LEFT), "Retrieving left camera image")

        #boxes are also converted only on display frames
        boxes: list[ZedObject2D] = []
        append = boxes.append
        ball_index = 0
        for obj in self._objects.object_list:
            raw_label = int(obj.raw_label)
            if raw_label != BALL_CLASS_ID:
                continue

            #stable ids were recorded in this same filtered order by get_objects()
            if ball_index >= len(self._current_ball_stable_ids):
                break
            stable_id = self._current_ball_stable_ids[ball_index]
            ball_index += 1

            bounding_box_2d = tuple((float(point[0]), float(point[1])) for point in obj.bounding_box_2d)
            append(ZedObject2D(object_id=stable_id, raw_label=raw_label, bounding_box_2d=bounding_box_2d))

        #get_data returns the sdk-backed BGRA numpy view without a full-frame color conversion
        return self._image_buffer.get_data(), boxes

    def get_camera_intrinsics(self) -> ZedCameraIntrinsics:
        """Return cached rectified left-camera calibration used for 3D-to-2D projection."""

        if self._intrinsics is not None:
            return self._intrinsics
        if self._zed is None:
            raise RuntimeError("ZED camera is closed")

        #read calibration once because it does not change while this camera is open
        info = self._zed.get_camera_information()
        configuration = info.camera_configuration
        camera = configuration.calibration_parameters.left_cam
        resolution = configuration.resolution
        self._intrinsics = ZedCameraIntrinsics(fx=float(camera.fx), fy=float(camera.fy), cx=float(camera.cx), cy=float(camera.cy), width=int(resolution.width), height=int(resolution.height))
        return self._intrinsics

    def get_camera_pose(self) -> ZedCameraPose | None:
        """Return the current left-camera pose in the gravity-aligned world frame for visualization."""

        if self._zed is None:
            raise RuntimeError("ZED camera is closed")
        if not self._frame_ready:
            raise RuntimeError("Call grab() successfully before get_camera_pose()")

        #pose is only needed when drawing world-space predictions back onto the camera image
        if self._camera_pose is None:
            self._camera_pose = sl.Pose()

        #world pose gives the transform from the current left-camera frame into the gravity-aligned world frame
        tracking_state = self._zed.get_position(self._camera_pose, sl.REFERENCE_FRAME.WORLD)
        if tracking_state != sl.POSITIONAL_TRACKING_STATE.OK:
            return None

        translation = self._camera_pose.get_translation().get()
        orientation = self._camera_pose.get_orientation().get()
        return ZedCameraPose(position=(float(translation[0]), float(translation[1]), float(translation[2])), orientation=(float(orientation[0]), float(orientation[1]), float(orientation[2]), float(orientation[3])))

    @property
    def last_frame_period_seconds(self) -> float | None:
        """Wall-clock period between the two most recent completed object frames."""

        if self._last_frame_period_ns is None:
            return None
        return self._last_frame_period_ns * 1e-9

    @property
    def application_fps(self) -> float | None:
        """Instantaneous application FPS from completed ZED object frames."""

        period = self.last_frame_period_seconds
        if period is None or period <= 0.0:
            return None
        return 1.0 / period

    @property
    def timing_stats(self) -> ZedTimingStats | None:
        """Rolling post-warmup application frame-rate statistics."""

        samples = self._timing_samples_ns
        count = len(samples)
        if count == 0 or self._last_frame_period_ns is None:
            return None

        #sorting happens only when stats are requested, never for every camera frame
        ordered = sorted(samples)
        mean_ns = sum(ordered) / count

        middle = count // 2
        if count % 2:
            median_ns = ordered[middle]
        else:
            median_ns = 0.5 * (ordered[middle - 1] + ordered[middle])

        p95_index = max(0, math.ceil(0.95 * count) - 1)
        p95_ns = ordered[p95_index]

        return ZedTimingStats(latest_seconds=self._last_frame_period_ns * 1e-9, mean_seconds=mean_ns * 1e-9, median_seconds=median_ns * 1e-9, p95_seconds=p95_ns * 1e-9, sample_count=count)

    @property
    def timing_warmup_remaining(self) -> int:
        """Number of startup frame intervals still excluded from rolling timing statistics."""

        return self._timing_warmup_remaining

    @staticmethod
    def _distance_squared(identity: _TrackedIdentity, x: float, y: float, z: float) -> float:
        """Squared distance from a stored track position to a new detection position."""

        #avoid np.linalg.norm and sqrt because only a threshold comparison is needed
        dx = x - identity.x
        dy = y - identity.y
        dz = z - identity.z
        return dx * dx + dy * dy + dz * dz

    def _bind_sdk_id(self, identity: _TrackedIdentity, sdk_id: int) -> None:
        """Move an existing stable identity to a new current SDK ID."""

        old_sdk_id = identity.sdk_id

        #remove the stale sdk lookup so one stable identity cannot remain mapped under two ids
        if old_sdk_id != sdk_id:
            if self._identities_by_sdk_id.get(old_sdk_id) is identity:
                del self._identities_by_sdk_id[old_sdk_id]
            identity.sdk_id = sdk_id

        self._identities_by_sdk_id[sdk_id] = identity

    def _resolve_identity(self, sdk_id: int, x: float, y: float, z: float, position_is_valid: bool) -> _TrackedIdentity:
        """Map the current SDK detection to the most likely stable application identity."""

        frame_number = self._frame_number
        existing = self._identities_by_sdk_id.get(sdk_id)
        native_id_was_reused = existing is not None

        #fast path when zed kept the same native id
        if existing is not None:
            gap = frame_number - existing.last_seen_frame

            #do not assign one stable identity to multiple detections in this same frame
            if gap <= self._max_missing_frames and existing.output_frame != frame_number:
                #if depth briefly fails, trust the continuing native id instead of creating a new track
                if not position_is_valid or not existing.has_valid_position:
                    return existing

                #same sdk id and physically close to the previous position means this is still the same object
                if self._distance_squared(existing, x, y, z) <= self._max_reassociation_distance_sq:
                    return existing

        #search recent stable tracks when the sdk has changed or reused its native id
        if position_is_valid:
            best: _TrackedIdentity | None = None
            best_distance_sq = self._max_reassociation_distance_sq

            for candidate in self._identities_by_stable_id.values():
                #do not reconsider the old object that failed the same-id validation above
                if candidate is existing:
                    continue
                #each stable id can only be emitted once per camera frame
                if candidate.output_frame == frame_number:
                    continue
                #distance reassociation requires a previous valid 3d position
                if not candidate.has_valid_position:
                    continue
                #only recently missing tracks are eligible for recovery
                if frame_number - candidate.last_seen_frame > self._max_missing_frames:
                    continue

                distance_sq = self._distance_squared(candidate, x, y, z)
                if distance_sq <= best_distance_sq:
                    best = candidate
                    best_distance_sq = distance_sq

            if best is not None:
                #remapped id if sdk temporarily loses track
                best.identity_changed = True
                self._bind_sdk_id(best, sdk_id)
                return best

        #no existing track matched, so create a new stable application identity
        identity = _TrackedIdentity(stable_id=self._next_stable_id, sdk_id=sdk_id, last_seen_frame=frame_number, x=x if position_is_valid else 0.0, y=y if position_is_valid else 0.0, z=z if position_is_valid else 0.0, has_valid_position=position_is_valid, identity_changed=native_id_was_reused)
        self._next_stable_id += 1
        self._identities_by_stable_id[identity.stable_id] = identity
        self._identities_by_sdk_id[sdk_id] = identity
        return identity

    def _resolve_identity_untracked(self, x: float, y: float, z: float, position_is_valid: bool) -> _TrackedIdentity:
        """Associate a direct frame detection using only recent 3D position, without ZED object tracking."""

        frame_number = self._frame_number
        best: _TrackedIdentity | None = None
        best_distance_sq = self._max_reassociation_distance_sq

        if position_is_valid:
            for candidate in self._identities_by_stable_id.values():
                if candidate.output_frame == frame_number:
                    continue
                if not candidate.has_valid_position:
                    continue
                if frame_number - candidate.last_seen_frame > self._max_missing_frames:
                    continue

                distance_sq = self._distance_squared(candidate, x, y, z)
                if distance_sq <= best_distance_sq:
                    best = candidate
                    best_distance_sq = distance_sq

        if best is not None:
            return best

        identity = _TrackedIdentity(stable_id=self._next_stable_id, sdk_id=-1, last_seen_frame=frame_number, x=x if position_is_valid else 0.0, y=y if position_is_valid else 0.0, z=z if position_is_valid else 0.0, has_valid_position=position_is_valid)
        self._next_stable_id += 1
        self._identities_by_stable_id[identity.stable_id] = identity
        return identity

    def _prune_identities(self) -> None:
        """Delete private identity records after they are too old to be reassociated."""

        minimum_frame = self._frame_number - self._max_missing_frames
        stale_ids = [stable_id for stable_id, identity in self._identities_by_stable_id.items() if identity.last_seen_frame < minimum_frame]

        for stable_id in stale_ids:
            identity = self._identities_by_stable_id.pop(stable_id)
            if identity.sdk_id >= 0 and self._identities_by_sdk_id.get(identity.sdk_id) is identity:
                del self._identities_by_sdk_id[identity.sdk_id]

    def close(self) -> None:
        """Release all ZED resources. Calling close() more than once is safe."""

        if self._zed is None:
            return

        self._zed.disable_object_detection()
        self._zed.disable_positional_tracking()
        self._zed.close()
        self._zed = None

        #invalidate data that referred to the closed camera
        self._frame_ready = False
        self._objects_ready = False
        self._image_buffer = None
        self._intrinsics = None
        self._camera_pose = None
        self._current_ball_stable_ids.clear()

    def __enter__(self) -> "ZedHandler":
        return self

    def __exit__(self, exc_type: object, exc_value: object, traceback: object) -> None:
        self.close()


